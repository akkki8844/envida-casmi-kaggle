"""Build the Kaggle CPU job that checks scripts/patch_aprior_bpi.py (runs on Kaggle, never locally: the APRIOR cell is
third-party notebook code).

    python kaggle_jobs/aprior_bpi_check/build.py <g498 notebook.ipynb>
Writes kaggle_jobs/aprior_bpi_check/job/{check_job.py, kernel-metadata.json}.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from patch_aprior_bpi import MARK, patch_source  # noqa: E402

BODY = r'''
import glob, json, os, shutil, subprocess, sys, tempfile, time
from pathlib import Path
try:
    import rdkit  # noqa
except ImportError:
    tag = "cp%d%d" % sys.version_info[:2]
    allw = sorted(glob.glob("/kaggle/input/**/rdkit*.whl", recursive=True))
    print("rdkit wheels:", [os.path.basename(w) for w in allw], "need", tag, flush=True)
    whl = [w for w in allw if "-" + tag + "-" in os.path.basename(w)]
    subprocess.run([sys.executable, "-m", "pip", "install", "--no-index", "--no-deps", whl[0]], check=True)
import rdkit
print("rdkit", rdkit.__version__, flush=True)

SUB = sorted(glob.glob("/kaggle/input/**/submission.csv", recursive=True))[0]
INP = Path(tempfile.mkdtemp(prefix="inp_"))
for f in ("train.parquet", "test.parquet"):
    src = sorted(glob.glob("/kaggle/input/**/" + f, recursive=True), key=lambda p: ("mass-spectra" not in p.lower(), len(p)))[0]
    os.symlink(src, INP / f)
N_TRAIN = 20000


def run_cell(src):
    ns = {"__name__": "aprior_check"}
    exec(compile(src, "aprior_cell", "exec"), ns)
    d = Path(tempfile.mkdtemp(prefix="work_"))
    shutil.copy(SUB, d / "submission.csv")
    tr = ns["ap_train"]
    ns["ap_train"] = lambda p, deadline=None: tr(p, n_train=N_TRAIN, trees=300, deadline=deadline)
    t0 = time.time()
    audit = ns["ap_run"](str(d), str(INP), True, cap_s=6000)
    audit["wall_s"] = round(time.time() - t0, 1)
    return (d / "submission.csv").read_bytes(), audit


def lists(b):
    import csv, io
    return {r[0]: r[1].split(";") for r in list(csv.reader(io.StringIO(b.decode(), newline="")))[1:]}


res = {}
b0, a0 = run_cell(ORIG); res["original"] = a0; print("original", json.dumps(a0, default=str), flush=True)
b1, a1 = run_cell(PATCH0); res["w0"] = a1; print("w0", json.dumps(a1, default=str), flush=True)
b2, a2 = run_cell(PATCH5); res["w05"] = a2; print("w05", json.dumps(a2, default=str), flush=True)
L0, L2 = lists(b0), lists(b2)
checks = dict(
    original_applied=a0.get("status") == "applied",
    w0_identical=b1 == b0,
    w05_applied=a2.get("status") == "applied",
    w05_bpi_ok=a2.get("bpi", {}).get("models") == ["[M+H]+", "[M-H]-"] and a2.get("bpi", {}).get("molecules", 0) > 300
               and not a2.get("bpi", {}).get("error"),
    same_molecules=list(L0) == list(L2),
    rank1_kept=all(L0[m][0] == L2[m][0] for m in L0),
    same_sets=all(sorted(L0[m]) == sorted(L2[m]) for m in L0),
    lists_reordered=sum(L0[m] != L2[m] for m in L0), lists=len(L0))
res["checks"] = checks
print("CHECKS", json.dumps(checks), flush=True)
Path("/kaggle/working/aprior_bpi_check.json").write_text(json.dumps(res, indent=1, default=str))
ok = all(v for k, v in checks.items() if k not in ("lists_reordered", "lists"))
print("ALL OK" if ok else "CHECK FAILED", flush=True)
'''


def main():
    nb = json.loads(Path(sys.argv[1]).read_text(encoding="utf8"))
    orig = "".join(next(c["source"] for c in nb["cells"] if "".join(c["source"]).startswith(MARK)))
    out = HERE / "job"
    out.mkdir(exist_ok=True)
    code = ('"""envida: Kaggle check of the APRIOR + BPI patch (generated by kaggle_jobs/aprior_bpi_check/build.py)."""\n'
            f"ORIG = {orig!r}\nPATCH0 = {patch_source(orig, 0.0)!r}\nPATCH5 = {patch_source(orig, 0.5)!r}\n" + BODY)
    (out / "check_job.py").write_text(code, encoding="utf8")
    meta = {"id": "govindmulchandani/envida-aprior-bpi-check", "title": "envida aprior bpi check", "code_file": "check_job.py",
            "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": False, "enable_internet": False,
            "dataset_sources": ["metric/rdkit-2026-3-3-wheel/1"], "kernel_sources": ["govindmulchandani/envida-casmi-v4"],
            "competition_sources": ["enveda-CASMI26-molecule-id-mass-spectra"],
            # the g498 notebook's own pinned image (python 3.10, matches the rdkit wheel)
            "docker_image": "gcr.io/kaggle-private-byod/python@sha256:37c64f7dd9c54116ecd1bcc88817c5469b88387388fade02bfa8bf3fc647d461"}
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf8")
    print("built", out)


if __name__ == "__main__":
    main()
